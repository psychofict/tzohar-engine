/**
 * Generate `src/lib/cjk-fonts.generated.ts` — the CJK webfonts THIS site's
 * locales actually need.
 *
 *     node scripts/gen-cjk-fonts.mjs          # write
 *     node scripts/gen-cjk-fonts.mjs --check  # verify (exits 1 on drift)
 *
 * WHY THIS IS GENERATED RATHER THAN A CONDITION
 *
 * `next/font/google` runs at COMPILE time: the call site alone downloads the
 * family, whether or not the result is ever used. Measured on an en-only client
 * build — 434 woff2 files either way, and 434 → 85 once the three calls are
 * removed. So `enabled.includes("ja") ? Noto_Sans_JP({...}) : null` buys nothing;
 * the call has to be absent from the compiled file, which means the file has to
 * differ per site. Same reasoning as `module-paths.ts`: a static artifact,
 * generated and committed, with `--check` to catch drift.
 *
 * WHAT IT COSTS TO GET WRONG
 *
 * Noto Sans KR/SC/JP are chunked into ~116 unicode-range files each, so three
 * unused families are 349 build-time requests to fonts.gstatic.com — 12.6 MB of
 * the 14.4 MB an English-only site was emitting, and 80% of its font fetches.
 * They are also a build DEPENDENCY on Google: a client deploy failed outright
 * when a handful of those URLs 404'd against a restored Vercel build cache, on a
 * site that serves no Japanese.
 *
 * OMITTING A FAMILY IS ONLY SAFE BECAUSE THE CSS WAS FIXED TO MATCH
 *
 * globals.css's `:lang(ko|zh|ja)` rules used to read `var(--font-ko),
 * var(--font-sans), system-ui` — which LOOKS like it degrades and does not. An
 * undefined custom property invalidates the whole declaration at computed-value
 * time, so the rest of the stack never applies and the browser uses its own
 * default: measured as Times New Roman for all body text on a build with no KR
 * family. The rules now carry an explicit `var(--font-ko, var(--font-sans))` plus
 * real system CJK faces, so a site that ships no webfont for a locale it serves
 * gets a proper CJK face. Do not remove those fallbacks.
 */
import { readFileSync, writeFileSync, existsSync } from "node:fs";

const OUT = "src/lib/cjk-fonts.generated.ts";
const CONFIG = "src/config/site.values.json";

/**
 * locale → the Google family that carries its script, and the CSS variable
 * globals.css looks for. `en` and `fr` are covered by the latin body font, so
 * they are deliberately absent.
 */
const CJK = {
  ko: { family: "Noto_Sans_KR", variable: "--font-ko", const: "notoSansKR" },
  zh: { family: "Noto_Sans_SC", variable: "--font-zh", const: "notoSansSC" },
  ja: { family: "Noto_Sans_JP", variable: "--font-ja", const: "notoSansJP" },
};

function enabledLocales() {
  if (!existsSync(CONFIG)) {
    // No config to read means we cannot know — emit nothing rather than guess a
    // set. Same fail-safe direction as the module-path table: the conservative
    // answer degrades to a system font, it does not delete anything.
    console.warn(`gen-cjk-fonts: ${CONFIG} not found; emitting no CJK fonts`);
    return [];
  }
  const cfg = JSON.parse(readFileSync(CONFIG, "utf8"));
  const list = cfg?.locales?.enabled;
  if (!Array.isArray(list)) {
    console.warn(`gen-cjk-fonts: ${CONFIG} has no locales.enabled; emitting no CJK fonts`);
    return [];
  }
  return list;
}

function render(locales) {
  const used = locales.filter((l) => CJK[l]).map((l) => [l, CJK[l]]);

  const header = `// GENERATED by scripts/gen-cjk-fonts.mjs — DO NOT EDIT.
// Run \`npm run cjk-fonts\` after changing \`locales.enabled\` in
// src/config/site.values.json. \`npm run cjk-fonts:check\` reports drift.
//
// Only the families this site's locales need are declared here, because a
// next/font call downloads its family at BUILD time even when unused — see the
// generator for the measurements.
`;

  if (used.length === 0) {
    return `${header}
/** This site enables no CJK locale, so it ships no CJK webfont. */
export const cjkVariableForLocale: Record<string, string> = {};
`;
  }

  const imports = used.map(([, c]) => c.family).join(", ");
  const decls = used
    .map(
      ([, c]) => `const ${c.const} = ${c.family}({
  variable: "${c.variable}",
  subsets: ["latin"],
  weight: ["400", "700"],
  display: "swap",
  preload: false,
});`,
    )
    .join("\n\n");
  const entries = used.map(([locale, c]) => `  ${locale}: ${c.const}.variable,`).join("\n");

  return `${header}import { ${imports} } from "next/font/google";

${decls}

/**
 * The variable class to put on <html> for the request's locale. The layout adds
 * only the current locale's, so a Korean page does not carry the Japanese face.
 */
export const cjkVariableForLocale: Record<string, string> = {
${entries}
};
`;
}

const locales = enabledLocales();
const next = render(locales);
const check = process.argv.includes("--check");
const current = existsSync(OUT) ? readFileSync(OUT, "utf8") : "";

if (check) {
  if (current !== next) {
    console.error(
      `gen-cjk-fonts: ${OUT} is out of date for locales [${locales.join(", ")}].\n` +
        `Run \`npm run cjk-fonts\` and commit the result.`,
    );
    process.exit(1);
  }
  console.log(`gen-cjk-fonts: ${OUT} is up to date`);
} else if (current === next) {
  console.log(`gen-cjk-fonts: ${OUT} unchanged`);
} else {
  writeFileSync(OUT, next);
  const shipped = locales.filter((l) => CJK[l]);
  console.log(
    `gen-cjk-fonts: wrote ${OUT} — ${shipped.length ? shipped.join(", ") : "no CJK locales"}`,
  );
}
