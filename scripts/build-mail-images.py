#!/usr/bin/env python3
"""Write src/lib/email/mail-images.generated.ts: the pictures our mail carries inside the message.

On 22 Oct 2026 Gmail showed the Ebenworks stamp broken in a product's mail: the file was there,
but ebenworks.co's name servers answered SERVFAIL often enough that Gmail's image proxy found no
address (EBE-4879). Every host under ebenworks.co, this one included, sits in that zone. So the
send carries each picture as an inline attachment (Content-ID) instead of a link: the shared kit's
`inlineImages(html, MAIL_IMAGES)` swaps each known `src` for `cid:<id>` (the stamp's bytes are in
the kit itself; this module adds this product's own pictures). EBE-4891.

The bytes ship as a module, not read from public/ at run time, so a Vercel function and the box's
fallback build carry them alike. scripts/mail-inline-images.test.ts holds each entry to its source file.
Run after a logo changes:  python3 scripts/build-mail-images.py
A WIDTH resizes the source for mail only (Pillow, LANCZOS), at twice the widest size a mail shows it.
"""
import base64
import hashlib
import io
import pathlib

ROOT = pathlib.Path(__file__).resolve().parents[1]
OUT = ROOT / "src/lib/email/mail-images.generated.ts"

# hosted address the mail names, Content-ID, file name, source in this repository, width or None
IMAGES = [
    # 1069x581 and 224 KB as served; mail shows it at most 150 px wide (supportDesk.ts), so 300.
    ("https://tzohar-sites.ebenworks.co/logo-light.png", "tzohar-logo", "tzohar-logo.png",
     "studio/public/logo-light.png", 300),
]


def png_bytes(source: pathlib.Path, width: int | None) -> bytes:
    data = source.read_bytes()
    if width is None:
        return data
    from PIL import Image  # only needed for a resized entry

    img = Image.open(io.BytesIO(data))
    img = img.resize((width, round(img.height * width / img.width)), Image.LANCZOS)
    out = io.BytesIO()
    img.save(out, format="PNG", optimize=True)
    return out.getvalue()


def main() -> None:
    images, sources = [], []
    for url, cid, filename, src, width in IMAGES:
        source = ROOT / src
        b64 = base64.b64encode(png_bytes(source, width)).decode("ascii")
        pieces = [b64[i:i + 100] for i in range(0, len(b64), 100)]
        body = "\n".join(f'      "{p}"' + (" +" if i < len(pieces) - 1 else ",") for i, p in enumerate(pieces))
        images.append(
            "  {\n"
            f'    url: "{url}",\n'
            f'    contentId: "{cid}",\n'
            f'    filename: "{filename}",\n'
            '    contentType: "image/png",\n'
            f"    content:\n{body}\n"
            "  },"
        )
        sha = hashlib.sha256(source.read_bytes()).hexdigest()
        sources.append(f'  {{ contentId: "{cid}", source: "{src}", sourceSha256: "{sha}", '
                       f'width: {"null" if width is None else width} }},')
    OUT.write_text(
        "// GENERATED by scripts/build-mail-images.py. Do not edit; change the source picture and run it again.\n"
        "// The pictures this product's mail carries inside the message (inline, Content-ID), EBE-4891.\n"
        'import type { InlineImage } from "./blocks.generated";\n\n'
        "export const MAIL_IMAGES: InlineImage[] = [\n" + "\n".join(images) + "\n];\n\n"
        "/** Where each picture came from, so a test fails when a source changes and this file did not. */\n"
        "export const MAIL_IMAGE_SOURCES = [\n" + "\n".join(sources) + "\n] as const;\n",
        encoding="utf-8",
    )
    print(f"wrote {OUT.relative_to(ROOT)} ({len(IMAGES)} picture(s), {OUT.stat().st_size} bytes)")


if __name__ == "__main__":
    main()
